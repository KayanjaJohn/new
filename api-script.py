def main():
    import argparse
    import sys
    
    parser = argparse.ArgumentParser(description='AutoDocGen - Generate API documentation from Python code')
    parser.add_argument('source', help='Source directory containing Python files')
    parser.add_argument('-o', '--output', default='api-docs.html', help='Output HTML file')
    parser.add_argument('--title', default='API Documentation', help='API title')
    
    args = parser.parse_args()
    
    if not os.path.isdir(args.source):
        print(f"Error: Directory not found: {args.source}")
        sys.exit(1)
    
    print(f"Scanning {args.source}...")
    parser = CodeParser(args.source)
    spec = parser.parse_all()
    spec.title = args.title
    
    print(f"Found {len(spec.endpoints)} endpoints and {len(spec.schemas)} schemas")
